app.post("/api/chat/clear", (req, res) => {
  const { sessionId } = req.body ?? {};

  if (typeof sessionId !== "string" || !sessionId.trim()) {
    return res.status(400).json({ error: "sessionId is required." });
  }

  // Chat history is stored by the frontend; acknowledge clearing this session.
  return res.json({ sessionId, cleared: true });
});

app.post("/api/chat", async (req, res) => {
  const body = req.body ?? {};
  const {
    sessionId,
    message,
    mode = "chat",
    messages = [],
    model: requestedModel,
    systemPrompt: customSystemPrompt,
  } = body;

  // ========================================
  // Validation
  // ========================================

  if (!sessionId || typeof sessionId !== "string") {
    return res.status(400).json({ error: "sessionId is required." });
  }

  if (!message || typeof message !== "string") {
    return res.status(400).json({ error: "message is required." });
  }

  if (!Array.isArray(messages)) {
    return res.status(400).json({ error: "messages must be an array." });
  }

  const normalizedMode = mode === "code" ? "code" : "chat";

  // 用户传了 model 就用用户的；否则回退到该模式的默认模型
  let selectedModel =
    typeof requestedModel === "string" && requestedModel.trim()
      ? requestedModel.trim()
      : DEFAULT_MODELS[normalizedMode];

  // ========================================
  // Prepare messages
  // ========================================

  const customPrompt =
    typeof customSystemPrompt === "string"
      ? customSystemPrompt.trim().slice(0, MAX_SYSTEM_PROMPT_LENGTH)
      : "";

  const systemMessage = {
    role: "system",
    content: customPrompt || SYSTEM_PROMPTS[normalizedMode],
  };

  const validMessages = messages.filter(
    (item) =>
      item &&
      (item.role === "user" || item.role === "assistant") &&
      typeof item.content === "string" &&
      item.content.trim() !== "",
  );

  const recentMessages = validMessages.slice(-MAX_CONTEXT_MESSAGES).map((item) => {
    const images = Array.isArray(item.images)
      ? item.images.filter((image) => typeof image === "string" && image.trim()).slice(0, 4)
      : [];
    return images.length ? { role: item.role, content: item.content, images } : { role: item.role, content: item.content };
  });
  const topLevelImages = Array.isArray(body.images)
    ? body.images.filter((image) => typeof image === "string" && image.trim()).slice(0, 4)
    : [];
  if (topLevelImages.length) {
    const lastUserIndex = recentMessages.findLastIndex((item) => item.role === "user");
    if (lastUserIndex >= 0) {
      const existing = recentMessages[lastUserIndex].images || [];
      recentMessages[lastUserIndex] = {
        ...recentMessages[lastUserIndex],
        images: [...existing, ...topLevelImages].slice(0, 4),
      };
    }
  }
  const ollamaMessages = [systemMessage, ...recentMessages];

  // Route image requests away from known text-only models to an installed vision model.
  const hasImageData = (value) => {
    if (typeof value === "string") {
      return /^(?:data:image\/[a-z0-9.+-]+;base64,)?[a-z0-9+/]{128,}={0,2}$/i.test(value.trim());
    }
    if (Array.isArray(value)) return value.some(hasImageData);
    if (!value || typeof value !== "object") return false;
    return Object.entries(value).some(([key, nested]) =>
      /^(images?|image_url|image)$/i.test(key) && hasImageData(nested),
    );
  };
  const containsImages = hasImageData(body.images) || hasImageData(messages);
  const normalizedModelName = selectedModel.toLowerCase().split(":")[0];
  const knownTextOnlyModel =
    /^(llama3(?:\.\d+)?|qwen2\.5-coder|deepseek-coder|codellama|phi[234]?|gemma(?:2)?|mistral|mixtral)(?:$|-)/i.test(normalizedModelName);

  if (containsImages && knownTextOnlyModel) {
    try {
      const response = await axios.get(`${OLLAMA_URL}/api/tags`, { timeout: 5000 });
      const availableModels = (response.data?.models || [])
        .map((item) => item?.name)
        .filter((name) => typeof name === "string");
      const preferred = ["qwen2.5vl:3b", "llava"];
      selectedModel = preferred.find((candidate) =>
        availableModels.some((name) =>
          candidate === "llava"
            ? name.toLowerCase() === "llava" || name.toLowerCase().startsWith("llava:")
            : name.toLowerCase() === candidate,
        ),
      ) || preferred[0];
    } catch (error) {
      console.warn(`[Chat] Could not list vision models; trying qwen2.5vl:3b: ${error.message}`);
      selectedModel = "qwen2.5vl:3b";
    }
  }

  const startTime = Date.now();

  console.log("");
  console.log(
    `${c.cyan}${c.bold}▶ [${timeStamp()}] ${selectedModel}${c.reset}` +
      `${c.dim} | mode=${normalizedMode} | ctx=${recentMessages.length}/${validMessages.length} msgs | session=${sessionId.slice(0, 16)}...${customPrompt ? ` | ${c.magenta}custom-prompt${c.dim}` : ""}${c.reset}`,
  );

  // ========================================
  // Cancellation
  // ========================================
  // 使用 res 的 close 事件：只有客户端在响应未完成时断开，才视为中断。
  // 正常结束时 res.writableFinished 为 true，不会误触发。

  const abortController = new AbortController();
  let clientGone = false;
  let finalized = false;
  let tokenCount = 0;
  let lastPrinted = 0;
  let sawDone = false;

  res.on("close", () => {
    if (!res.writableFinished) {
      clientGone = true;
      abortController.abort();
    }
  });

  // ========================================
  // Request Ollama
  // ========================================

  let upstream;
  try {
    upstream = await axios.post(
      `${OLLAMA_URL}/api/chat`,
      {
        model: selectedModel,
        messages: ollamaMessages,
        stream: true,
        options: {
          num_predict: MAX_OUTPUT_TOKENS,
          num_ctx: NUM_CTX,
        },
      },
      {
        responseType: "stream",
        timeout: OLLAMA_TIMEOUT_MS,
        signal: abortController.signal,
        validateStatus: () => true, // 非 2xx 由下方统一处理
      },
    );
  } catch (error) {
    if (clientGone) return;
    console.error("Chat API error:", error.message);
    return res.status(502).json({
      error: "Failed to communicate with Ollama.",
    });
  }

  // 非 2xx：Ollama 返回 JSON 错误体（响应是流，需要读完再解析）
  if (upstream.status < 200 || upstream.status >= 300) {
    let errorMessage = "Failed to communicate with Ollama.";
    try {
      const body = await readStreamToString(upstream.data);
      const parsed = JSON.parse(body);
      if (typeof parsed.error === "string" && parsed.error.trim()) {
        errorMessage = parsed.error.trim();
      }
    } catch {
      // 保留通用错误信息
    }

    console.error(`[Chat] Ollama HTTP ${upstream.status}: ${errorMessage}`);
    if (clientGone) return;
    return res.status(mapUpstreamStatus(upstream.status)).json({
      error: errorMessage,
    });
  }

  // ========================================
  // Start Streaming Response to client
  // ========================================

  res.status(200);
  res.setHeader("Content-Type", "application/x-ndjson");
  res.setHeader("Cache-Control", "no-cache");
  res.setHeader("Connection", "keep-alive");
  res.setHeader("X-Accel-Buffering", "no");
  res.flushHeaders();

  const decoder = new StringDecoder("utf8");
  let buffer = "";

  // 向客户端写入一帧，响应已结束或已断开时静默忽略
  const send = (payload) => {
    if (finalized || res.writableEnded || res.destroyed) return;
    res.write(JSON.stringify(payload) + "\n");
  };

  // 结束响应（只执行一次），可选地先发送错误帧
  const finalize = (errorMessage) => {
    if (finalized) return;
    finalized = true;

    if (!res.writableEnded && !res.destroyed) {
      if (errorMessage) {
        res.write(JSON.stringify({ error: errorMessage, done: true }) + "\n");
      }
      res.end();
    }
  };

  const handleLine = (line) => {
    const trimmed = line.trim();
    if (!trimmed) return;

    let data;
    try {
      data = JSON.parse(trimmed);
    } catch {
      console.error(
        "[Chat] invalid NDJSON line from Ollama:",
        trimmed.slice(0, 200),
      );
      return;
    }

    // Ollama 在生成中途报错
    if (data.error) {
      clearLine();
      console.error(
        `${c.red}[Chat] Ollama stream error: ${data.error}${c.reset}`,
      );
      finalize(String(data.error));
      upstream.data.destroy();
      return;
    }

    if (typeof data.message?.content === "string" && data.message.content) {
      tokenCount += 1;
      send({ content: data.message.content, done: false });

      if (tokenCount - lastPrinted >= 5) {
        lastPrinted = tokenCount;
        const elapsed = (Date.now() - startTime) / 1000;
        const tps = elapsed > 0 ? tokenCount / elapsed : 0;
        clearLine();
        process.stdout.write(
          `  ${c.yellow}⏳ ${tokenCount} tokens | ${tps.toFixed(1)} tok/s | ${elapsed.toFixed(1)}s${c.reset}`,
        );
      }
    }

    if (data.done) {
      sawDone = true;
      send({ content: "", done: true, model: selectedModel });
      clearLine();

      const evalCount = data.eval_count || tokenCount;
      const evalSec = (data.eval_duration || 0) / 1e9;
      const totalSec =
        (data.total_duration || 0) / 1e9 || (Date.now() - startTime) / 1000;
      const loadSec = (data.load_duration || 0) / 1e9;
      const promptCount = data.prompt_eval_count || 0;
      const tps = evalSec > 0 ? evalCount / evalSec : 0;

      console.log(
        `  ${c.green}✓ ${evalCount} tokens | ${tps.toFixed(1)} tok/s` +
          `${c.dim} | prompt ${promptCount} tok | ` +
          `生成 ${evalSec.toFixed(2)}s | 总计 ${totalSec.toFixed(2)}s` +
          (loadSec > 0.1 ? ` | 加载 ${loadSec.toFixed(2)}s` : "") +
          `${c.reset}`,
      );
    }
  };

  // Ollama 的 chunk 可能在任意位置切开一行 JSON，必须按 '\n' 缓冲后再解析
  upstream.data.on("data", (chunk) => {
    if (finalized) return;

    // 多字节 UTF-8 字符可能被切开，StringDecoder 会保留不完整的字节
    buffer += decoder.write(chunk);

    let newlineIndex;
    while ((newlineIndex = buffer.indexOf("\n")) !== -1) {
      const line = buffer.slice(0, newlineIndex);
      buffer = buffer.slice(newlineIndex + 1);
      handleLine(line);
      if (finalized) return;
    }
  });

  upstream.data.on("end", () => {
    buffer += decoder.end();
    if (buffer.trim() && !finalized) {
      handleLine(buffer);
    }
    buffer = "";

    if (finalized) return;

    if (!sawDone && !clientGone) {
      console.error("[Chat] Ollama stream ended before done frame.");
      finalize("Ollama 连接在生成完成前中断。");
    } else {
      finalize();
    }
  });

  upstream.data.on("error", (error) => {
    if (clientGone) {
      finalized = true;
      return;
    }
    console.error("Ollama stream error:", error.message);
    finalize("Ollama stream failed.");
  });

  // 客户端主动停止或关闭页面：打印统计并标记为已结束
  res.on("close", () => {
    if (clientGone && !finalized) {
      finalized = true;
      clearLine();
      const elapsed = (Date.now() - startTime) / 1000;
      console.log(
        `  ${c.red}✗ 已停止${c.reset}${c.dim} | ${tokenCount} tokens | ${elapsed.toFixed(1)}s | session=${sessionId.slice(0, 16)}...${c.reset}`,
      );
    }
  });
});

// ========================================
// Start Server
// ========================================

const server = app.listen(PORT, () => {
  console.log(`Server running at http://localhost:${PORT}`);
  console.log(`Ollama URL: ${OLLAMA_URL}`);
  console.log(`CORS origins: ${CORS_ORIGINS.join(", ")}`);
  console.log(`Max context messages: ${MAX_CONTEXT_MESSAGES}`);
  console.log(`Max output tokens: ${MAX_OUTPUT_TOKENS}`);
  console.log(`Context window (num_ctx): ${NUM_CTX}`);
});

server.on("error", (error) => {
  if (error.code === "EADDRINUSE") {
    console.error(
      `Port ${PORT} is already in use. Stop the other process or change PORT in .env.`,
    );
  } else {
    console.error("Server error:", error);
  }
  process.exit(1);
});
