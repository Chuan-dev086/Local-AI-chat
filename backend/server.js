function timeStamp() {
  const d = new Date();
  const pad = (n) => String(n).padStart(2, "0");
  return `${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`;
}

// clear the current line (only meaningful in a TTY)
function clearLine() {
  if (process.stdout.isTTY) {
    process.stdout.write("\r\x1b[2K");
  }
}

