// Read a small upstream stream (e.g. an error body) fully as text
function readStreamToString(stream) {
  return new Promise((resolve, reject) => {
    const decoder = new StringDecoder("utf8");
    let text = "";
    stream.on("data", (chunk) => {
      text += decoder.write(chunk);
    });
    stream.on("end", () => resolve(text + decoder.end()));
    stream.on("error", reject);
  });
}

// Map an upstream HTTP status to the status we return to the browser
function mapUpstreamStatus(upstreamStatus) {
  if (upstreamStatus === 400) return 400;
  if (upstreamStatus === 404) return 404;
  return 502;
}

