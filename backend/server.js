import express from "express";
import cors from "cors";
import axios from "axios";
import "dotenv/config";
import { StringDecoder } from "string_decoder";

const app = express();

// ========================================
// Configuration (from backend/.env)
// ========================================

const PORT = Number(process.env.PORT) || 5000;
const OLLAMA_URL = process.env.OLLAMA_URL || "http://localhost:11434";

// 允许访问后端的前端来源，多个用英文逗号分隔
const CORS_ORIGINS = (
  process.env.CORS_ORIGINS || "http://localhost:5173,http://127.0.0.1:5173"
)
  .split(",")
  .map((origin) => origin.trim())
  .filter(Boolean);

// 用户没主动选模型时，各模式的默认值
const DEFAULT_MODELS = {
  chat: process.env.DEFAULT_CHAT_MODEL || "llama3.2:3b",
  code: process.env.DEFAULT_CODE_MODEL || "qwen2.5-coder:3b",
};

// Maximum number of previous messages sent to Ollama
const MAX_CONTEXT_MESSAGES = Number(process.env.MAX_CONTEXT_MESSAGES) || 10;

// Maximum number of tokens generated by the model
const MAX_OUTPUT_TOKENS = Number(process.env.MAX_OUTPUT_TOKENS) || 1024;

// Context window passed to Ollama (prompt + history + output must fit)
const NUM_CTX = Number(process.env.NUM_CTX) || 8192;

// Maximum length of a custom system prompt
const MAX_SYSTEM_PROMPT_LENGTH =
  Number(process.env.MAX_SYSTEM_PROMPT_LENGTH) || 8000;

// Maximum timeout for a single Ollama generation (ms)
const OLLAMA_TIMEOUT_MS = Number(process.env.OLLAMA_TIMEOUT_MS) || 300000;

// ========================================
// Process-level safety nets
// ========================================

process.on("unhandledRejection", (reason) => {
  console.error("[Process] unhandled rejection:", reason);
});

process.on("uncaughtException", (error) => {
  console.error("[Process] uncaught exception:", error);
});

// ========================================
// Middleware
// ========================================

app.use(
  cors({
    origin(origin, callback) {
      // 没有 Origin 头的请求（curl、服务端调用）直接放行
      if (!origin) return callback(null, true);
      // 不在白名单内的来源：不设置 CORS 响应头，浏览器会拒绝读取响应
      return callback(null, CORS_ORIGINS.includes(origin));
    },
  }),
);

app.use(express.json({ limit: "20mb" }));

