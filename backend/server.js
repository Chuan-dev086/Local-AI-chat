import express from "express";
import cors from "cors";
import axios from "axios";
import "dotenv/config";

const app = express();

app.use(cors());
app.use(express.json());

// ========================================
// Configuration (from backend/.env)
// ========================================

const PORT = Number(process.env.PORT) || 5000;
const OLLAMA_URL = process.env.OLLAMA_URL || "http://localhost:11434";

// 用户没主动选模型时，各模式的默认值
const DEFAULT_MODELS = {
  chat: process.env.DEFAULT_CHAT_MODEL || "llama3.2:3b",
  code: process.env.DEFAULT_CODE_MODEL || "qwen2.5-coder:3b",
};

// Maximum number of previous messages sent to Ollama
const MAX_CONTEXT_MESSAGES = Number(process.env.MAX_CONTEXT_MESSAGES) || 10;

// Maximum number of tokens generated by the model
const MAX_OUTPUT_TOKENS = Number(process.env.MAX_OUTPUT_TOKENS) || 1024;

// Maximum length of a custom system prompt
const MAX_SYSTEM_PROMPT_LENGTH =
  Number(process.env.MAX_SYSTEM_PROMPT_LENGTH) || 8000;
// ========================================
// Terminal Colors & Log Helpers
// ========================================

const supportsColor = process.stdout.isTTY;

const c = {
  reset: supportsColor ? "\x1b[0m" : "",
  bold: supportsColor ? "\x1b[1m" : "",
  dim: supportsColor ? "\x1b[90m" : "",
  cyan: supportsColor ? "\x1b[36m" : "",
  green: supportsColor ? "\x1b[32m" : "",
  yellow: supportsColor ? "\x1b[33m" : "",
  red: supportsColor ? "\x1b[31m" : "",
  magenta: supportsColor ? "\x1b[35m" : "",
};

function timeStamp() {
  const d = new Date();
  const pad = (n) => String(n).padStart(2, "0");
  return `${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`;
}

// clear the current line
function clearLine() {
  if (process.stdout.isTTY) {
    process.stdout.write("\r\x1b[2K");
  }
}

const SYSTEM_PROMPTS = {
  chat: `
You are a friendly and helpful AI assistant.

Rules:
- Detect the language used by the user.
- If the user writes in English, answer in English.
- If the user writes in Chinese, answer in Chinese.
- If the user writes in Malay, answer in Malay.
- Keep your answers natural and easy to understand.
- Do not claim to have real-world experiences.
- Unless the user explicitly asks for code, do not provide code.
`,

  code: `
You are a professional programming assistant.

Rules:
- Detect the language used by the user.
- If the user writes in English, answer in English.
- If the user writes in Chinese, answer in Chinese.
- If the user writes in Malay, answer in Malay.
- Explain programming concepts clearly.
- When code is requested, provide complete working code when appropriate.
- Help debug errors and explain why they happen.
- Pay attention to validation, edge cases and asynchronous errors.
- Do not make unnecessary assumptions about the user's project.
`,
};

// ========================================
// Session Metadata
// ========================================
//
// We no longer use this Map as the source
// of conversation history.
//
// React/localStorage is the source of truth
// for chat messages.
//
// The Map can still store lightweight
// session information for future features.
//
const sessions = new Map();

// ========================================
// Health Check
// ========================================

app.get("/api/health", (req, res) => {
  res.json({
    status: "ok",
    ollama: OLLAMA_URL,
  });
});

// ========================================
// List Available Models (from Ollama)
// ========================================

app.get("/api/models", async (req, res) => {
  try {
    const response = await axios.get(`${OLLAMA_URL}/api/tags`, {
      timeout: 5000,
    });

    const models = (response.data.models || [])
      .map((m) => m.name)
      .filter(Boolean)
      .sort();

    res.json({ models });
  } catch (error) {
    console.error("[Models] failed to fetch:", error.message);
    res.status(500).json({
      error: "Failed to fetch model list from Ollama.",
    });
  }
});

// ========================================
// Chat API
// ========================================

app.post("/api/chat", async (req, res) => {
  const {
    sessionId,
    message,
    mode = "chat",
    messages = [],
    model: requestedModel,
    systemPrompt: customSystemPrompt,
  } = req.body;

  // ========================================
  // Validation
  // ========================================

  if (!sessionId || typeof sessionId !== "string") {
    return res.status(400).json({
      error: "sessionId is required.",
    });
  }

  if (!message || typeof message !== "string") {
    return res.status(400).json({
      error: "message is required.",
    });
  }

  if (!Array.isArray(messages)) {
    return res.status(400).json({
      error: "messages must be an array.",
    });
  }

  const normalizedMode = mode === "code" ? "code" : "chat";

  // 用户传了 model 就用用户的；否则回退到该模式的默认模型
  const selectedModel =
    typeof requestedModel === "string" && requestedModel.trim()
      ? requestedModel.trim()
      : DEFAULT_MODELS[normalizedMode];

  // ========================================
  // Save lightweight session metadata
  // ========================================

  sessions.set(sessionId, {
    mode: normalizedMode,
    updatedAt: new Date().toISOString(),
  });

  // ========================================
  // Prepare System Message
  // ========================================

  const customPrompt =
    typeof customSystemPrompt === "string"
      ? customSystemPrompt.trim().slice(0, MAX_SYSTEM_PROMPT_LENGTH)
      : "";

  const systemMessage = {
    role: "system",
    content: customPrompt || SYSTEM_PROMPTS[normalizedMode],
  };

  // ========================================
  // Validate Conversation Messages
  // ========================================

  const validMessages = messages.filter(
    (item) =>
      item &&
      (item.role === "user" || item.role === "assistant") &&
      typeof item.content === "string" &&
      item.content.trim() !== "",
  );

  // ========================================
  // Limit Context
  // ========================================

  const recentMessages = validMessages.slice(-MAX_CONTEXT_MESSAGES);

  // ========================================
  // Prepare Ollama Messages
  // ========================================

  const ollamaMessages = [systemMessage, ...recentMessages];

  const startTime = Date.now();

  console.log("");
  console.log(
    `${c.cyan}${c.bold}▶ [${timeStamp()}] ${selectedModel}${c.reset}` +
      `${c.dim} | mode=${normalizedMode} | ctx=${recentMessages.length}/${validMessages.length} msgs | session=${sessionId.slice(0, 16)}...${customPrompt ? ` | ${c.magenta}custom-prompt${c.dim}` : ""}${c.reset}`,
  );

  try {
    // ========================================
    // Start Streaming Response
    // ========================================

    res.status(200);

    res.setHeader("Content-Type", "application/x-ndjson");

    res.setHeader("Cache-Control", "no-cache");

    res.setHeader("Connection", "keep-alive");

    res.setHeader("X-Accel-Buffering", "no");

    // ========================================
    // Request Ollama
    // ========================================

    const response = await axios.post(
      `${OLLAMA_URL}/api/chat`,
      {
        model: selectedModel,

        messages: ollamaMessages,

        stream: true,

        options: {
          num_predict: MAX_OUTPUT_TOKENS,
        },
      },
      {
        responseType: "stream",
        timeout: 300000,
      },
    );

    let fullResponse = "";
    let tokenCount = 0;
    let lastPrinted = 0;
    let finishedNormally = false;

    // ========================================
    // Receive Ollama Chunks
    // ========================================

    response.data.on("data", (chunk) => {
      const text = chunk.toString();

      const lines = text.split("\n").filter((line) => line.trim() !== "");

      for (const line of lines) {
        try {
          const data = JSON.parse(line);

          // -------------------------------
          // AI generated text
          // -------------------------------

          if (data.message?.content) {
            const content = data.message.content;

            fullResponse += content;
            tokenCount += 1;

            res.write(
              JSON.stringify({
                content,
                done: false,
              }) + "\n",
            );

            // 每 5 个 token 刷新一次进度行
            if (tokenCount - lastPrinted >= 5) {
              lastPrinted = tokenCount;
              const elapsed = (Date.now() - startTime) / 1000;
              const tps = tokenCount / elapsed;
              clearLine();
              process.stdout.write(
                `  ${c.yellow}⏳ ${tokenCount} tokens | ${tps.toFixed(1)} tok/s | ${elapsed.toFixed(1)}s${c.reset}`,
              );
            }
          }

          // -------------------------------
          // Generation finished
          // -------------------------------

          if (data.done) {
            finishedNormally = true;

            res.write(
              JSON.stringify({
                content: "",
                done: true,
                model: selectedModel,
              }) + "\n",
            );

            // ---- 打印最终统计 ----
            clearLine();

            const evalCount = data.eval_count || tokenCount;
            const evalSec = (data.eval_duration || 0) / 1e9;
            const totalSec =
              (data.total_duration || 0) / 1e9 ||
              (Date.now() - startTime) / 1000;
            const loadSec = (data.load_duration || 0) / 1e9;
            const promptCount = data.prompt_eval_count || 0;

            const tps = evalSec > 0 ? evalCount / evalSec : 0;

            console.log(
              `  ${c.green}✓ ${evalCount} tokens | ${tps.toFixed(1)} tok/s` +
                `${c.dim} | prompt ${promptCount} tok | ` +
                `生成 ${evalSec.toFixed(2)}s | 总计 ${totalSec.toFixed(2)}s` +
                (loadSec > 0.1 ? ` | 加载 ${loadSec.toFixed(2)}s` : "") +
                `${c.reset}`,
            );
          }
        } catch (error) {
          console.error("Failed to parse Ollama chunk:", error);
        }
      }
    });
    // ========================================
    // Ollama Stream Finished
    // ========================================

    response.data.on("end", () => {
      if (!res.writableEnded) {
        res.end();
      }
    });
    // ========================================
    // Ollama Stream Error
    // ========================================

    response.data.on("error", (error) => {
      console.error("Ollama stream error:", error);

      if (!res.writableEnded) {
        res.write(
          JSON.stringify({
            error: "Ollama stream failed.",
            done: true,
          }) + "\n",
        );

        res.end();
      }
    });

    // ========================================
    // Browser Disconnected
    // ========================================

    req.on("close", () => {
      if (!res.writableEnded) {
        // if don't have create finish,consider user not complete
        if (!finishedNormally) {
          clearLine();
          const elapsed = (Date.now() - startTime) / 1000;
          console.log(
            `  ${c.red}✗ 已停止${c.reset}${c.dim} | ${tokenCount} tokens | ${elapsed.toFixed(1)}s | session=${sessionId.slice(0, 16)}...${c.reset}`,
          );
        }

        response.data.destroy();
      }
    });
  } catch (error) {
    console.error("Chat API error:", error.message);

    if (res.headersSent) {
      if (!res.writableEnded) {
        res.write(
          JSON.stringify({
            error:
              error.response?.data?.error ||
              "Failed to communicate with Ollama.",
            done: true,
          }) + "\n",
        );

        res.end();
      }

      return;
    }

    res.status(500).json({
      error:
        error.response?.data?.error || "Failed to communicate with Ollama.",
    });
  }
});

// ========================================
// Start Server
// ========================================

app.listen(PORT, () => {
  console.log(`Server running at http://localhost:${PORT}`);

  console.log(`Ollama URL: ${OLLAMA_URL}`);

  console.log(`Max context messages: ${MAX_CONTEXT_MESSAGES}`);

  console.log(`Max output tokens: ${MAX_OUTPUT_TOKENS}`);
});
